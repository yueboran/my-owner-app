// 辅助函数：根据城市名称或 ID 获取默认文脉资料
export function getPredefinedCulture(cityIdOrName: string): PredefinedCityCulture | undefined {
  if (!cityIdOrName) return undefined;
  if (DEFAULT_CULTURAL_DATABASE[cityIdOrName]) {
    return DEFAULT_CULTURAL_DATABASE[cityIdOrName];
  }
  // 尝试根据城市名寻找
  const clean = cityIdOrName.trim().replace(/(市|地区|盟|州)$/, '');
  for (const item of Object.values(DEFAULT_CULTURAL_DATABASE)) {
    if (
      item.cityName === clean ||
      item.cityName.includes(clean) ||
      clean.includes(item.cityName)
    ) {
      return item;
    }
  }
  return undefined;
}
